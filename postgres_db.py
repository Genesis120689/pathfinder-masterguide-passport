"""PostgreSQL connection layer for the Passport application.

Uses Supabase's session pooler DATABASE_URL. No fallback to temporary SQLite:
a missing or invalid URL fails startup rather than silently losing accounts.
"""
import os
import re
import psycopg
from psycopg.rows import dict_row
from psycopg import errors

IntegrityError = psycopg.IntegrityError

SCHEMA = """
CREATE TABLE IF NOT EXISTS clubs (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name TEXT NOT NULL, mission TEXT NOT NULL, church TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name TEXT NOT NULL, username TEXT UNIQUE NOT NULL, password TEXT NOT NULL,
 role TEXT NOT NULL, club_id BIGINT REFERENCES clubs(id),
 level TEXT NOT NULL DEFAULT 'Friend', certified INTEGER NOT NULL DEFAULT 0,
 created TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS progress (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL, level TEXT NOT NULL, req_key TEXT NOT NULL,
 status TEXT NOT NULL DEFAULT 'not_started', submitted_by BIGINT,
 approved_by BIGINT, updated TEXT, notes TEXT, UNIQUE(user_id,level,req_key)
);
CREATE TABLE IF NOT EXISTS approvals (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL, kind TEXT NOT NULL, stage TEXT NOT NULL,
 approved_by BIGINT NOT NULL, created TEXT NOT NULL, UNIQUE(user_id,kind,stage)
);
CREATE TABLE IF NOT EXISTS audits (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 actor BIGINT, subject BIGINT, action TEXT, detail TEXT, created TEXT
);
CREATE TABLE IF NOT EXISTS appointments (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL, stage TEXT NOT NULL, approved_by BIGINT NOT NULL,
 created TEXT NOT NULL, UNIQUE(user_id,stage)
);
CREATE TABLE IF NOT EXISTS announcements (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 title TEXT NOT NULL, body TEXT NOT NULL, image_path TEXT,
 created_by BIGINT NOT NULL, created TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 title TEXT NOT NULL, description TEXT NOT NULL, starts_at TEXT NOT NULL,
 ends_at TEXT, location TEXT, scope TEXT NOT NULL,
 club_id BIGINT, created_by BIGINT NOT NULL, created TEXT NOT NULL
);
"""

def connect():
    url = os.environ.get("DATABASE_URL", "").strip()
    if not url or "[YOUR-PASSWORD]" in url:
        raise RuntimeError("Configure a valid Supabase DATABASE_URL in Render first")
    return Connection(psycopg.connect(url, row_factory=dict_row, connect_timeout=12))

class Cursor:
    def __init__(self, cursor, lastrowid=None):
        self.cursor = cursor
        self.lastrowid = lastrowid
    def fetchone(self):
        return self.cursor.fetchone()
    def fetchall(self):
        return self.cursor.fetchall()
    def __iter__(self):
        return iter(self.cursor)

class Connection:
    def __init__(self, raw):
        self.raw = raw
    def __enter__(self):
        return self
    def __exit__(self, exc_type, exc, tb):
        if exc_type:
            self.raw.rollback()
        else:
            self.raw.commit()
        self.raw.close()
    def execute(self, sql, params=None):
        sql = sql.strip()
        if sql.upper() == "BEGIN IMMEDIATE":
            return Cursor(self.raw.execute("SELECT 1"))
        sql = re.sub(r'"(admin|completed|pending|mg|director|mission|ssd|club|masterguide|trainee)"', r"'\1'", sql)
        sql = sql.replace("INSERT OR IGNORE INTO ", "INSERT INTO ")
        ignore = "INSERT OR IGNORE" in sql.upper() or (
            sql.startswith("INSERT INTO approvals(") or
            sql.startswith("INSERT INTO appointments(")
        )
        if ignore and "ON CONFLICT" not in sql.upper():
            sql += " ON CONFLICT DO NOTHING"
        sql = sql.replace("?", "%s")
        inserted = bool(re.match(r"INSERT INTO (clubs|users|announcements|events)\\b", sql, re.I))
        if inserted and "RETURNING" not in sql.upper():
            sql += " RETURNING id"
        cur = self.raw.execute(sql, params)
        if inserted:
            record = cur.fetchone()
            return Cursor(cur, record["id"] if record else None)
        return Cursor(cur)
    def executescript(self, script):
        self.raw.execute(script)
